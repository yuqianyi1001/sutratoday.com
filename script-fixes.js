// 简体 → 繁体的修正字典。
// OpenCC 按现代台湾用字选字，佛典的写法常常不同；这里列出转错的字词，转换之后逐条替换。
// 要加一条：在 TRADITIONAL_FIXES 里加一行 [正则, "正确写法"]，再把 global-script-toggle.js 里的 ?v= 加 1。
// scripts/convert_to_traditional.py 里有同一套规则（给 md 里的译文用），改这里时那边也要改。

export const TRADITIONAL_FIXES = [
  // ── 整字替换：这些字在佛典里几乎都写作右边的字
  [/唸/g, "念"], // 念佛、念誦
  [/[燻薰]/g, "熏"], // 熏習
  [/慾/g, "欲"], // 欲界、貪欲
  [/纔/g, "才"],
  [/喫/g, "吃"],
  [/羣/g, "群"],
  [/牀/g, "床"],
  [/捱/g, "挨"],
  [/侷/g, "局"], // 局限
  [/汙/g, "污"], // 染污，与 CBETA 一致
  [/擡/g, "抬"],
  [/鍊/g, "煉"], // 修煉
  [/痴/g, "癡"], // 愚癡、貪瞋癡

  // ── 看上下文
  [/瞭(?!望)/g, "了"], // 明了、了解；只有“瞭望”用“瞭”
  [/佈(?=施|教|薩|道)/g, "布"], // 布施、布教、布薩
  [/流佈/g, "流布"],
  [/宣佈/g, "宣布"],
  [/([佛經偈論故所古頌疏律藏師祖章節品卷文謂曰])雲/g, "$1云"], // 經云、師云：“云”是“说”
  [/捨(?=利[弗子]|衛[國城]|那|身城|摩|頭)/g, "舍"], // 舍利弗、舍衛國
  [/迴(?=答|來|去|頭|覆|報|應|話|歸|到|家|國|復)/g, "回"], // 回答、回來；“迴向”不变
  [/屍(?=棄|羅|利沙|婆|吉|城|叉|迦)/g, "尸"], // 尸羅、憍尸迦
  [/([婆伐鉢缽])屍/g, "$1尸"], // 毗婆尸、僧伽伐尸沙、毘鉢尸
  [/鹹(?=[言皆共歸悉同稱謂知來以作各曰得令使見聞願陽])/g, "咸"], // 咸言、咸皆：“咸”是“都”
  [/睏/g, "困"], // 疲困、困乏
  [/(?<![一二三四五六七八九十兩幾每這那此某半])隻(?=能|應)/g, "只"], // 只能、只應；“一隻能…”的量词不改
  [/幹(?=擾|涉|預)/g, "干"], // 干擾、干涉、干預
  [/([親鄉鄰])裡/g, "$1里"], // 親里、鄉里、鄰里
  [/製(?=度)/g, "制"], // 制度
  [/矇(?=住)/g, "蒙"], // 蒙住
  [/佔(?=卜)|(?<=筮)佔/g, "占"], // 占卜、筮占
  [/準(?=許|予)/g, "准"], // 准許、准予
  [/(?<=規)製/g, "制"], // 規制
  [/(?<=場)閤/g, "合"], // 場合
  [/(?<![寄依憑委拜付囑請推假信])託(?=腮|著)/g, "托"], // 托腮、手托著；寄託著等不改
  [/(?<=長)幹(?=寺|里)/g, "干"], // 長干寺、長干里

  // ── 卷：经卷的“卷”不是“捲起”的“捲”
  [/捲(?=[上下中第])/g, "卷"],
  [/捲(?=[一二三四五六七八九十百千零〇两兩0-9])/g, "卷"],
  [/([全共][一二三四五六七八九十百千零〇两兩0-9]*)捲/g, "$1卷"],
];

export function fixTraditional(text) {
  if (!text) {
    return text;
  }
  for (const [pattern, replacement] of TRADITIONAL_FIXES) {
    text = text.replace(pattern, replacement);
  }
  return text;
}
