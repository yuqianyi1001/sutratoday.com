sections = re.split(r'(### 现代语译\n)', content)
# sections[0] is everything before first ### 现代语译
# sections[1] is "### 现代语译\n"
# sections[2] is the empty space before next ### 原文
# and so on...

new_content = sections[0]
for i in range(len(translations)):
    new_content += sections[2*i + 1] # "### 现代语译\n"
    # sections[2*i + 2] has the original empty space and the next segment's start
    # We need to replace only the empty part until next ### 原文 or end of string
    next_part = sections[2*i + 2]
    match = re.match(r'(\s*)(\n### 原文|\Z)', next_part, re.DOTALL)
    if match:
        new_content += "\n" + translations[i] + "\n" + next_part[len(match.group(1)):]
    else:
        # Fallback if structure is slightly different
        new_content += "\n" + translations[i] + "\n" + next_part

with open(file_path, "w", encoding="utf-8") as f:
    f.write(new_content)
