pattern = re.compile(r'(### 现代语译\n)(.*?)(\n### 原文|\Z)', re.DOTALL)
matches = list(pattern.finditer(content))

# Find the first 20 empty ones (excluding already filled ones)
empty_indices = [i for i, m in enumerate(matches) if not m.group(2).strip()]

for i in range(min(len(translations), len(empty_indices))):
    idx = empty_indices[i]
    m = matches[idx]
    old_text = m.group(0)
    new_text = m.group(1) + "\n" + translations[i] + "\n" + m.group(3)
    content = content.replace(old_text, new_text, 1)

with open(file_path, "w", encoding="utf-8") as f:
    f.write(content)
