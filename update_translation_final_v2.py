file_path = "content/sutras-raw/T0221-001.md"

with open(file_path, 'r', encoding='utf-8') as f:
    content = f.read()

for key, value in translations.items():
    escaped_key = re.escape(key)
    regex_pattern = r"(### 原文\s*" + escaped_key + r"\s*### 现代语译\s*)"
    match = re.search(regex_pattern, content, re.MULTILINE | re.DOTALL)
    if match:
        rest = content[match.end():].strip()
        if not rest or rest.startswith("###"):
            content = content[:match.end()] + value + "\n" + content[match.end():]

with open(file_path, 'w', encoding='utf-8') as f:
    f.write(content)
